#!/usr/bin/env python3
"""
Round 40 (November 2026): units ("fact || joke") for the steady screens,
the ones people see most: a day that doesn't change, its evening (from
5 pm), its night (from 10 pm) and a day that stays cold. At On and 11,
both languages, written by shape (docs/SHAPES.md). Each situation was
asked first what it gives a joke (round 39's lesson): no decision to make
and nothing to blame on the weather; the screen with nothing to do; plans
or none; bed and phones; the reader's cold-weather habits.

    python3 review/rounds/make_round40.py

Reads review/rounds/2026-11-steady/<lang>.raw.json, writes
review/rounds/2026-11-steady.json and review/rounds/2026-11-steady/critic.md.
After the vote, build_pools.py puts kept units in (units_10/11.<key>).
"""

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent
ROUND = "2026-11-steady"
LEVEL = {"10": "On", "11": "11"}
# steady_night has no facts list: its units carry their own sentence, as the live ones do.
NIGHT = {"en": ["This works for the rest of the night.", "You're dressed right for the rest of the night.", "Nothing changes tonight."],
         "de": ["Was du anhast, passt für den Rest der Nacht."]}
SPRITE = {"steady": "sweater_dry", "steady_evening": "jacket_dry", "steady_night": "jacket_dry", "steady_cold": "coat_dry"}
NAME = {"steady": "Steady day", "steady_evening": "Steady evening", "steady_night": "Steady night", "steady_cold": "Cold all day"}
MEANING = {"steady": "Nothing changes all day: about half of all screens.",
           "steady_evening": "Nothing changes for the rest of the evening (5 pm to 10 pm). The reader may or may not be going out.",
           "steady_night": "Nothing changes for the rest of the night (from 10 pm). The one time bed is fair game.",
           "steady_cold": "Winter coat weather, all day: about a fifth of winter mornings."}
SHAPE = {"screen": "the screen's own limits", "credit": "taking credit, denying blame", "sting": "ends on a sting word",
         "habit": "your habits, predicted", "quote": "your words thrown back", "jab": "a jab at you",
         "parent": "the parent's scold", "self": "the Grantler about himself", "sigh": "the Grantler's sigh",
         "people": "other people", "simile": "a simile", "other": "outside the strong shapes, for variety"}


def main():
    rows, cuts = [], []
    for lang in ("en", "de"):
        facts = json.loads((REPO / "prototypes" / "fact-flavour" / "lang" / f"{lang}.json").read_text(encoding="utf-8"))["facts"]
        raw = json.loads((HERE / ROUND / f"{lang}.raw.json").read_text(encoding="utf-8"))
        for key in ("steady", "steady_evening", "steady_night", "steady_cold"):
            sentences = NIGHT[lang] if key == "steady_night" else facts[key]
            for level, items in raw[key].items():
                for x in items:
                    if x.get("cut"):
                        cuts.append((lang, f"{key} · {LEVEL[level]}", x["joke"], x["cut"]))
                        continue
                    fact = sentences[x["fact"] % len(sentences)].replace("{AM}", "")
                    rows.append({"lang": lang, "path": f"unit_{level}.{key}", "text": f"{fact} || {x['joke']}",
                                 "role": "unit", "sprite": SPRITE[key], "new": True,
                                 "batch": f"{NAME[key]}: {LEVEL[level]}",
                                 "meaning": f"{MEANING[key]} At {LEVEL[level]}: the sentence and its joke as one.",
                                 "hint": "Shape: " + SHAPE[x["shape"]]})
    (HERE / f"{ROUND}.json").write_text(json.dumps({"round": ROUND, "idPrefix": "sd", "lines": rows},
                                                   ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    out = ["# Round 40: the critic's cuts", "",
           "Generated by `make_round40.py`. Every line written is in `<lang>.raw.json`;",
           "these were cut before the vote, by the rules in `docs/CRITIC.md`.", ""]
    out += [f"- **{lang}, {slot}** {text}  \n  _{why}_" for lang, slot, text, why in cuts]
    (HERE / ROUND / "critic.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    for l in ("en", "de"):
        by = {}
        for r in rows:
            if r["lang"] == l:
                by[r["batch"]] = by.get(r["batch"], 0) + 1
        print(l, sum(by.values()), by)
    print("cut before the vote:", len(cuts))


if __name__ == "__main__":
    main()
