#!/usr/bin/env python3
"""
Turns the review page's votes into files the repo keeps.

    python3 tools/review_sync.py <decisions.json> [--fixes]

<decisions.json> is either the page's "Save decisions file" export
({"decisions": [...]}) or a plain list of decision documents, which is
what Claude gets when it reads the page's database directly.

Writes, per language:

    review/decisions/<lang>.json   every vote ever cast, keyed by line id.
                                   The memory: a vetoed line never comes back.
    review/examples/<lang>.md      starred lines, by key and level. The
                                   writer's examples for the next round.
    review/dont/<lang>.md          vetoed lines with their tags and notes.
                                   The writer's "don't" list.
    review/rewrite/<lang>.md       the "Write new" votes still waiting for
                                   new lines: what the screen shows there,
                                   the lines that are out, the owner's note.

"Write new" (verdict "rewrite") is a veto that asks for more: the line is
out, the line it would have replaced is out too (build_pools.py takes
both out), and that spot gets completely new lines, not variations. Both
lines go on the "don't" list. A spot leaves the waiting list once a line
from a later round that "answers" it (the round row's "answers": the
vote's id) is starred or kept.

With --key=review/rounds/<round>.key.json it also prints the votes per
batch with the name behind each letter: the result of a blind round.

A vote can carry "edit": the owner's rewording, typed on the page (round
8). It is kept with the vote; build_pools.py applies it.

With --fixes it also writes build/review/<lang>_fixes.json for
tools/apply_review.py: vetoed shipped lines are deleted, starred or kept
candidates are appended. Review it with --dry-run before applying.
"""

import collections
import json
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
OUT = REPO / "review"
LEVEL_NAME = {"0": "plain", "10": "dry", "11": "sarcastic"}
FIELDS = ("lang", "level", "key", "path", "text", "source", "batch", "round",
          "verdict", "tags", "note", "edit", "updatedAt")


def load_votes(path):
    data = json.loads(pathlib.Path(path).read_text(encoding="utf-8"))
    if isinstance(data, dict):
        data = data.get("decisions", data.get("docs", []))
    votes = []
    for d in data:
        d = d.get("data", d) if isinstance(d, dict) and "data" in d else d
        if d.get("id") and d.get("lang") and d.get("text"):
            votes.append(d)
    return votes


def merge(lang, votes):
    target = OUT / "decisions" / f"{lang}.json"
    known = json.loads(target.read_text(encoding="utf-8")) if target.exists() else {}
    changed = 0
    for v in votes:
        old = known.get(v["id"])
        if old and old.get("updatedAt", "") >= v.get("updatedAt", ""):
            continue
        known[v["id"]] = {k: v.get(k, "") for k in FIELDS if k != "lang"}
        changed += 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(dict(sorted(known.items())), ensure_ascii=False, indent=1) + "\n",
                      encoding="utf-8")
    return known, changed


def round_rows():
    """Every round's lines, by (round, language, text): what the page showed with each."""
    rows = {}
    for f in sorted((OUT / "rounds").glob("*.json")):
        data = json.loads(f.read_text(encoding="utf-8"))
        if isinstance(data, dict) and isinstance(data.get("lines"), list):
            for line in data["lines"]:
                rows[(data.get("round", ""), line.get("lang", ""), line.get("text", ""))] = line
    return rows


def grouped(known, verdict):
    verdicts = verdict if isinstance(verdict, tuple) else (verdict,)
    by = collections.defaultdict(list)
    for d in known.values():
        if d.get("verdict") in verdicts:
            by[(d["key"].removesuffix("_j"), d["key"], d["level"])].append(d)
    return sorted(by.items())


def write_examples(lang, known):
    lines = [f"# Starred lines ({lang})", "",
             "Generated by `tools/review_sync.py` from the review page. These",
             "are the owner's taste: write the next round to sit beside them.",
             "Do not edit by hand; vote on the page instead.", ""]
    for (_, key, level), items in grouped(known, "star"):
        lines.append(f"## {key} · {LEVEL_NAME.get(level, level)}")
        lines.append("")
        # A line the owner reworded on the page is starred as reworded.
        for d in sorted(items, key=lambda d: d.get("edit") or d["text"]):
            lines.append(f"- {d.get('edit') or d['text']}" + (f"  \n  _{d['note']}_" if d.get("note") else ""))
        lines.append("")
    path = OUT / "examples" / f"{lang}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def write_dont(lang, known, rows):
    vetoed = [d for d in known.values() if d.get("verdict") in ("veto", "rewrite")]
    tags = collections.Counter(t for d in vetoed for t in d.get("tags") or [])
    lines = [f"# Vetoed lines ({lang})", "",
             "Generated by `tools/review_sync.py`. Never reuse these lines or",
             "their skeletons. Tags say why.", ""]
    if tags:
        lines.append("Most common reasons: " + ", ".join(f"{t} ({n})" for t, n in tags.most_common()) + ".")
        lines.append("")
    for (_, key, level), items in grouped(known, ("veto", "rewrite")):
        lines.append(f"## {key} · {LEVEL_NAME.get(level, level)}")
        lines.append("")
        for d in sorted(items, key=lambda d: d["text"]):
            why = ", ".join((["write new"] if d.get("verdict") == "rewrite" else []) + (d.get("tags") or [])) or "no tag"
            lines.append(f"- {d['text']}  \n  _{why}" + (f": {d['note']}" if d.get("note") else "") + "_")
            # "Write new" on a line that would replace another: that one is out too.
            old = replaced(d, rows, lang)
            if old:
                lines.append(f"- {old}  \n  _write new (the line it would have replaced)_")
        lines.append("")
    path = OUT / "dont" / f"{lang}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def replaced(d, rows, lang):
    """The line a "Write new" vote also takes out, if its round row replaces one."""
    if d.get("verdict") != "rewrite":
        return ""
    row = rows.get((d.get("round", ""), lang, d.get("text", ""))) or {}
    old = row.get("replaces") or ""
    return "" if old == "*" else old


def waiting(lang, known, rows):
    """The "Write new" votes no starred or kept line from a later round answers yet."""
    answered = set()
    for d in known.values():
        if d.get("verdict") in ("star", "keep"):
            row = rows.get((d.get("round", ""), lang, d.get("text", ""))) or {}
            if row.get("answers"):
                answered.add(row["answers"])
    return [(i, d) for i, d in sorted(known.items()) if d.get("verdict") == "rewrite" and i not in answered]


def write_waiting(lang, known, rows):
    todo = waiting(lang, known, rows)
    lines = [f"# Waiting for new lines ({lang})", "",
             "Generated by `tools/review_sync.py`: every \"Write new\" vote no",
             "kept line answers yet. Write completely new lines for each spot,",
             "not variations of what's out (it's all in `review/dont/`), and give",
             "each new row `\"answers\": \"<id>\"` in the next round's file.", ""]
    if not todo:
        lines.append("Nothing waiting.")
    by = collections.defaultdict(list)
    for i, d in todo:
        by[d.get("path", "").split("[")[0]].append((i, d))
    for path, items in sorted(by.items()):
        lines.append(f"## {path}")
        lines.append("")
        for i, d in items:
            row = rows.get((d.get("round", ""), lang, d.get("text", ""))) or {}
            lines.append(f"- **Out:** {d['text']}")
            old = replaced(d, rows, lang)
            if old:
                lines.append(f"  **And the line it would have replaced:** {old}")
            elif row.get("replaces") == "*":
                lines.append("  **It would have replaced:** every wording of this situation")
            if d.get("note"):
                lines.append(f"  **Wanted instead:** {d['note']}")
            if d.get("tags"):
                lines.append(f"  **Tags:** {', '.join(d['tags'])}")
            screen = [x for x in (row.get("sprite") and f"drawing {row['sprite']}",
                                  row.get("fact") and f"above it: “{row['fact']}”",
                                  row.get("under") and f"under it: “{row['under']}”") if x]
            if screen:
                lines.append(f"  **On screen:** {'; '.join(screen)}")
            if row.get("meaning"):
                lines.append(f"  **What it's for:** {row['meaning']}")
            lines.append(f"  **Answers:** `{i}` ({d.get('round', '')})")
        lines.append("")
    path = OUT / "rewrite" / f"{lang}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return len(todo)


def write_fixes(lang, known):
    doc = json.loads((REPO / "lang" / f"{lang}.json").read_text(encoding="utf-8"))
    out = []
    for d in known.values():
        m = re.match(r"^((?:temp|precip)_\d+)\.([a-z_]+)", d["path"])
        if not m:
            continue
        section, key = m.groups()
        current = (doc.get(section) or {}).get(key) or []
        if d.get("source") == "candidate":
            if d.get("verdict") in ("star", "keep") and d["text"] not in current:
                out.append({"path": f"{section}.{key}[{len(current)}]", "old": "", "new": d["text"],
                            "why": f"{d['verdict']} in review" + (f" ({d['round']})" if d.get("round") else "")})
        elif d.get("verdict") in ("veto", "rewrite") and d["text"] in current:
            # Locate by text, not by the stored index: the file may have
            # moved since the vote.
            i = current.index(d["text"])
            out.append({"path": f"{section}.{key}[{i}]", "old": d["text"], "new": None,
                        "why": "vetoed: " + (", ".join(d.get("tags") or []) or "no tag")})
    target = REPO / "build" / "review" / f"{lang}_fixes.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps({"summary": "From the review page.", "replacements": out},
                                 ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return target, len(out)


def batch_results(votes, key_path):
    key = {}
    for kp in (key_path or "").split(","):
        if kp:
            key.update(json.loads(pathlib.Path(kp).read_text(encoding="utf-8")))
    tally = collections.defaultdict(collections.Counter)
    for v in votes:
        if v.get("batch") and v.get("verdict"):
            tally[(v.get("round", ""), v["lang"], v["batch"])][v["verdict"]] += 1
    print("\nby batch (stars, keeps, vetoes; score = 2 per star + 1 per keep - 2 per veto):")
    rows = []
    for (rnd, lang, batch), c in tally.items():
        score = 2 * c["star"] + c["keep"] - 2 * c["veto"]
        rows.append((rnd, lang, -score, batch, c, score))
    for rnd, lang, _, batch, c, score in sorted(rows):
        name = key.get(batch, {}).get("voice", "") or key.get(batch, {}).get("style", "")
        print(f"  {rnd:18} {lang} {batch} {name:14} {c['star']:3} {c['keep']:3} {c['veto']:3}   score {score:+d}")


def main():
    key_path = next((a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--key=")), None)
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__.strip())
        return 2
    votes = load_votes(args[0])
    by_lang = collections.defaultdict(list)
    for v in votes:
        by_lang[v["lang"]].append(v)
    if any(v.get("batch") for v in votes):
        batch_results(votes, key_path)
    rows = round_rows()
    for lang, vs in sorted(by_lang.items()):
        known, changed = merge(lang, vs)
        write_examples(lang, known)
        write_dont(lang, known, rows)
        open_spots = write_waiting(lang, known, rows)
        counts = collections.Counter(d.get("verdict") or "tag/note only" for d in known.values())
        print(f"{lang}: {changed} new or changed, now " + ", ".join(f"{n} {k}" for k, n in sorted(counts.items())))
        if open_spots:
            print(f"    {open_spots} spot(s) waiting for new lines -> review/rewrite/{lang}.md")
        if "--fixes" in sys.argv:
            target, n = write_fixes(lang, known)
            print(f"    {n} fix(es) -> {target.relative_to(REPO)}  (apply: python3 tools/apply_review.py {target.relative_to(REPO)} --dry-run)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
